// Which jobs a person holds, and how much: everyone holds all six (a base of 1), and each answer that counts adds 1.
// Returns the six, the biggest first (ties keep the order of JOB_IDS), each { id, score, share, why: [reasons] }.
function jobRoles(a, signals = JOB_SIGNALS) {
  a = a || {};
  const rows = JOB_IDS.map((id, k) => {
    const why = (signals[id] || []).filter(s => !!s[2](a)).map(s => s[1]);
    return { id, k, score: 1 + why.length, why };
  });
  const total = rows.reduce((t, r) => t + r.score, 0);
  return rows
    .sort((p, q) => q.score - p.score || p.k - q.k)
    .map(r => ({ id: r.id, score: r.score, share: r.score / total, why: r.why }));
}
// The first n jobs (the reveal shows 3).
function jobTop(a, n = 3, signals = JOB_SIGNALS) {
  return jobRoles(a, signals).slice(0, n);
}

// ---------- admin hours ----------
// The state of a list of sureness levels (1 Guess, 2 Close, 3 Exact): any Guess makes a Guess, all Exact makes Exact.
function jobState(cfs) {
  const L = (cfs || []).filter(v => v != null);
  if (!L.length || L.some(v => v <= 1)) return "Guess";
  return L.every(v => v >= 3) ? "Exact" : "Close";
}
// The minutes a month of each job and the total. mins: { id: { v, cf } } (the taps); a job with no tap counts at
// JOB_DEFAULT as a Guess. Returns { rows: [{ id, min, cf, given }], total, st }.
function jobAdmin(mins, defaults = JOB_DEFAULT) {
  mins = mins || {};
  const rows = JOB_IDS.map(id => {
    const m = mins[id];
    return m && m.v != null && isFinite(m.v) && m.v >= 0
      ? { id, min: +m.v, cf: m.cf || 2, given: true }
      : { id, min: defaults[id] || 0, cf: 1, given: false };
  });
  return { rows, total: rows.reduce((t, r) => t + r.min, 0), st: jobState(rows.map(r => r.cf)) };
}

// ---------- tasks and the four exits ----------
// The minutes a month of one task: { per: minutes each time, times: times a year }.
function jobTaskMonthly(t) {
  if (!t || !(t.per >= 0) || !(t.times >= 0)) return 0;
  return (t.per * t.times) / 12;
}
// "saves you ~X min/month": never 0 for a task that takes time, so a small saving still shows as progress.
function jobSaveWords(min) {
  if (!(min > 0)) return null;
  return "saves you ~" + Math.max(1, Math.round(min)) + " min/month";
}
// The lines of Show the math for one task.
function jobTaskMath(t) {
  const m = jobTaskMonthly(t);
  return [
    "About " +
      t.per +
      " min each time, " +
      t.times +
      (t.times === 1 ? " time" : " times") +
      " a year = " +
      Math.round(t.per * t.times) +
      " min a year.",
    Math.round(t.per * t.times) + " min a year ÷ 12 months = about " + Math.max(1, Math.round(m)) + " min a month.",
    "The time each task takes is a guess for a typical person. Your own time can be more or less.",
  ];
}
// Whether an exit takes a task off the plate.
function jobIsOff(e) {
  return JOB_OFF.includes(e);
}
// Running it and Living it. admin: the result of jobAdmin. tasks: [{ id, role, per, times }]. exits: { taskId: 'auto'
// | 'hand' | 'drop' | 'do' }. Each job gives back the minutes of its tasks off the plate, at most the minutes of that
// job. Returns { before, living, running, pct, better, byRole: { id: { n, m, saved, min } } }.
//   before: the hours of the job as the person said (or the Guess), with every task on their plate.
//   living: the minutes given back. running: before minus living. pct: living as a share of before.
//   better: the percent shown ("N% better"): at least 1 once a minute is given back, never 0 then.
function jobLiving(admin, tasks, exits) {
  exits = exits || {};
  const byRole = {};
  (admin.rows || []).forEach(r => {
    byRole[r.id] = { n: 0, m: 0, raw: 0, saved: 0, min: r.min };
  });
  (tasks || []).forEach(t => {
    const b = byRole[t.role];
    if (!b) return;
    b.m++;
    if (jobIsOff(exits[t.id])) {
      b.n++;
      b.raw += jobTaskMonthly(t);
    }
  });
  let living = 0;
  Object.values(byRole).forEach(b => {
    b.saved = Math.min(b.raw, b.min);
    living += b.saved;
    delete b.raw;
  });
  const before = admin.total || 0,
    pct = before > 0 ? (living / before) * 100 : 0;
  return {
    before,
    living,
    running: Math.max(0, before - living),
    pct,
    better: living > 0 ? Math.max(1, Math.round(pct)) : 0,
    byRole,
  };
}
// Minutes as words: "45 min", "1 hr", "2.5 hrs".
function jobHoursWords(min) {
  const m = Math.max(0, Math.round(min || 0));
  if (m < 60) return m + " min";
  const h = Math.round((m / 60) * 10) / 10;
  return h === 1 ? "1 hr" : h + " hrs";
}
// The line under the two bars, in "1% better" words. Never "0%".
function jobBetterWords(L) {
  if (!L || !(L.living > 0)) return "Move one task off your plate and this starts at 1% better.";
  return L.better + "% better: " + jobHoursWords(L.living) + " a month back for living.";
}

// ---------- a goal wired to an account (feature 4) ----------
// The days the money of a wired goal can move. 'pay' follows the paycheck (the default).
const JOB_WIRE_DAYS = [
  ["pay", "Each payday"],
  ["d1", "The 1st"],
  ["d15", "The 15th"],
  ["1and15", "The 1st and 15th"],
];
// The deposits a year of a day choice. payPerYear: the paychecks a year of the person (the caller works it out
// from the pay frequency, with the game's own periods()). A payday that varies counts as 12.
function jobWireTimes(day, payPerYear) {
  if (day === "d1" || day === "d15") return 12;
  if (day === "1and15") return 24;
  return payPerYear > 0 ? payPerYear : 12;
}
// The amount of each deposit that covers the monthly amount: monthly × 12 ÷ deposits a year, rounded up to a whole
// dollar. Empty is not zero: no monthly amount gives null.
function jobWirePer(monthly, times) {
  if (!(monthly > 0) || !(times > 0)) return null;
  return Math.ceil((monthly * 12) / times - 1e-9);
}
// An ISO date n months later. A day past the end of the month moves to the last day (Jan 31 + 1 month = Feb 28).
function jobAddMonths(iso, n) {
  const [y, m, d] = String(iso).slice(0, 10).split("-").map(Number);
  const t = y * 12 + (m - 1) + n,
    Y = Math.floor(t / 12),
    M = t - Y * 12;
  const last = new Date(Date.UTC(Y, M + 1, 0)).getUTCDate();
  return Y + "-" + String(M + 1).padStart(2, "0") + "-" + String(Math.min(d, last)).padStart(2, "0");
}
// The quarterly check-in of a wired goal: 3 months after the last check-in, or after the day it was wired.
// Returns { next, due }: due once today is on or after next.
function jobCheckNext(set, last, today) {
  const next = jobAddMonths(last || set, 3);
  return { next, due: String(today) >= next };
}

// ---------- the dates of the health and insurance quests (feature 5) ----------
// The person taps their own date (a month and a day, as 'MM-DD'): an open enrollment window's last day, an FSA
// deadline, a policy's renewal day. The reminder shows from `lead` days before the date to the date itself.
// Returns { date: the next such date on or after today, open: whether the reminder shows, days: days to go }.
function jobDateNext(md, today, lead = 30) {
  if (!/^\d\d-\d\d$/.test(String(md || ""))) return null;
  const y = +String(today).slice(0, 4),
    [mm, dd] = md.split("-").map(Number);
  const at = Y => {
    const last = new Date(Date.UTC(Y, mm, 0)).getUTCDate();
    return Y + "-" + String(mm).padStart(2, "0") + "-" + String(Math.min(dd, last)).padStart(2, "0");
  };
  const date = at(y) >= String(today).slice(0, 10) ? at(y) : at(y + 1);
  const days = Math.round(
    (Date.parse(date + "T00:00:00Z") - Date.parse(String(today).slice(0, 10) + "T00:00:00Z")) / 86400000
  );
  return { date, days, open: days <= lead };
}

// ---------- the household role map: who carries what (feature 6) ----------
// The value of one hour of admin work, in dollars. First the person's own time price for chores (the swipes of
// "What your hours are worth"), then their real pay per hour from the time ledger. Empty is not zero: with
// neither, the rate is null and no dollar value shows (the hours still show).
function jobHourValue(tpChores, wage) {
  if (tpChores > 0 && isFinite(tpChores)) return { rate: +tpChores, from: "tp" };
  if (wage > 0 && isFinite(wage)) return { rate: +wage, from: "wage" };
  return { rate: null, from: null };
}
// Who carries what. The household shares the admin time of the six jobs:
//   admin: the result of jobAdmin. tasks, exits: as for jobLiving.
//   hands: { taskId: key } for each task handed off to a person of the household (a coach or a tool is not one).
//   assign: { jobId: [keys] }: who holds each job. A job with nobody tapped stays with people[0] (the player).
//   people: [{ key, n }], people[0] is the player. Any number of people. rate: dollars an hour, or null.
// For each job: the time left on the plate (the job's minutes minus what jobLiving gives back) is split equally
// between its holders. A task handed to a person goes to that person, at the same cap as jobLiving (when the tasks
// off the plate add up to more than the job's minutes, each is scaled down by the same factor). Tasks automated,
// dropped, or handed to a coach or a tool leave the household.
// Returns { people: [{ key, n, min, value, share, jobs: { jobId: min } }], total, value, rate, byJob }.
//   total: the household's admin minutes a month (the sum of the people). value: total ÷ 60 × rate (null with no
//   rate). share: one person's part of the total (0 to 1). byJob: { jobId: { holders, left, handed } }.
function jobCarry(admin, tasks, exits, hands, assign, people, rate) {
  exits = exits || {};
  hands = hands || {};
  assign = assign || {};
  const P = (people || []).filter(p => p && p.key != null),
    known = new Set(P.map(p => p.key));
  const out = P.map(p => ({ key: p.key, n: p.n, min: 0, value: null, share: 0, jobs: {} }));
  const at = k => out.find(p => p.key === k);
  const give = (k, id, m) => {
    const p = at(k);
    if (!p || !(m > 0)) return;
    p.min += m;
    p.jobs[id] = (p.jobs[id] || 0) + m;
  };
  const byJob = {};
  (admin && admin.rows ? admin.rows : []).forEach(r => {
    const mine = (tasks || []).filter(t => t.role === r.id && jobIsOff(exits[t.id]));
    const raw = mine.reduce((s, t) => s + jobTaskMonthly(t), 0),
      f = raw > 0 ? Math.min(1, r.min / raw) : 0;
    const left = Math.max(0, r.min - Math.min(raw, r.min));
    let holders = (assign[r.id] || []).filter((k, i, a) => known.has(k) && a.indexOf(k) === i);
    if (!holders.length && P.length) holders = [P[0].key];
    holders.forEach(k => give(k, r.id, left / holders.length));
    const handed = {};
    mine.forEach(t => {
      const k = hands[t.id];
      if (exits[t.id] !== "hand" || !known.has(k)) return;
      const m = jobTaskMonthly(t) * f;
      give(k, r.id, m);
      handed[k] = (handed[k] || 0) + m;
    });
    byJob[r.id] = { holders, left, handed };
  });
  const total = out.reduce((s, p) => s + p.min, 0),
    ok = rate > 0 && isFinite(rate);
  out.forEach(p => {
    p.share = total > 0 ? p.min / total : 0;
    p.value = ok ? (p.min / 60) * rate : null;
  });
  return { people: out, total, value: ok ? (total / 60) * rate : null, rate: ok ? +rate : null, byJob };
}

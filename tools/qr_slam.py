#!/usr/bin/env python3
"""Make docs/qr-slam.png: the QR code of the link for the slide (the front door of SLAM the Game).

Run:    python3 tools/qr_slam.py            writes docs/qr-slam.png and game/data/qr.js
        python3 tools/qr_slam.py --check    also reads both pictures back and compares them with the link

It also writes game/data/qr.js: the same code as an SVG picture for the game's own sheet "Share" (Me, then
Share the game), so the code in the game and the code on the slide open the same address.
Needs:  pip install qrcode pillow           (and, for --check only: pip install opencv-python-headless)

The link is LINK below. It must be the same as DOOR_LINK in game/account/door.js and the link in
docs/LAUNCH-LINK.md: test/launch-link.test.js fails when the three differ. When the link changes, change
all three, then run this file again. No web service is used: the picture is made on this machine.
"""
import os
import sys

LINK = "https://play.stresslessaboutmoney.com/game/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "qr-slam.png")
MIN_WIDTH = 1000  # pixels
QUIET = 4  # modules of white around the code (the QR standard asks for 4)


def make():
    import qrcode
    from qrcode.constants import ERROR_CORRECT_Q

    # Q: a quarter of the code can be covered or blurred (a projector, a phone held at an angle) and it still reads.
    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_Q, border=QUIET, box_size=1)
    qr.add_data(LINK)
    qr.make(fit=True)
    modules = qr.modules_count + 2 * QUIET
    qr.box_size = -(-MIN_WIDTH // modules)  # round up, so each module is a whole number of pixels
    img = qr.make_image(fill_color="black", back_color="white").convert("L")
    img.save(OUT, optimize=True)
    return img.size[0], qr.modules_count


GAME_JS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "game", "data", "qr.js")
GAME_HEAD = """/* ============================================================================
   SLAM the Game: data/qr.js
   PURPOSE     Data only. One QR code as an SVG picture (window.QR_SVG), and the address that the code
               contains (window.QR_URL). The sheet "Share" in ui.js shows them. No logic.
   INPUT       Nothing.
   OUTPUT      Two constants: window.QR_URL and window.QR_SVG.
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. tools/qr_slam.py makes it from the link for the slide (the public
               address of the game), together with docs/qr-slam.png. test/launch-link.test.js fails when
               the address here differs from that link.
   ========================================================================= */
"""


def game():
    """The same code as an SVG picture for the game: one small square for each dark module, on white."""
    import qrcode
    from qrcode.constants import ERROR_CORRECT_Q

    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_Q, border=0, box_size=1)
    qr.add_data(LINK)
    qr.make(fit=True)
    rows = qr.get_matrix()
    n = len(rows)
    side = n + 2 * QUIET
    path = "".join(f"M{x + QUIET},{y + QUIET}h1v1h-1z" for y, row in enumerate(rows) for x, dark in enumerate(row) if dark)
    svg = (
        f'<svg viewBox="0 0 {side} {side}" role="img" aria-label="QR code for the game" shape-rendering="crispEdges">'
        f'<rect width="{side}" height="{side}" fill="#fff"/><path d="{path}"/></svg>'
    )
    with open(GAME_JS, "w", encoding="utf-8") as f:
        f.write(GAME_HEAD + f'window.QR_URL = "{LINK}";\nwindow.QR_SVG =\n  \'{svg}\';\n')
    return n


def check_game():
    """Draw the SVG of game/data/qr.js as a picture again (from its path), and read it with OpenCV."""
    import re

    import cv2
    import numpy as np

    js = open(GAME_JS, encoding="utf-8").read()
    side = int(re.search(r'viewBox="0 0 (\d+) ', js).group(1))
    img = np.full((side, side), 255, dtype=np.uint8)
    for x, y in re.findall(r"M(\d+),(\d+)h1v1h-1z", js):
        img[int(y), int(x)] = 0
    big = cv2.cvtColor(cv2.resize(img, (side * 12, side * 12), interpolation=cv2.INTER_NEAREST), cv2.COLOR_GRAY2BGR)
    for reader in (cv2.QRCodeDetectorAruco(), cv2.QRCodeDetector()):
        got = reader.detectAndDecode(big)[0]
        if got:
            return got
    return ""


def check():
    import cv2

    # Two readers of OpenCV, at full size and at a phone-screen size. One exact read is enough.
    img = cv2.imread(OUT)
    got = ""
    for reader in (cv2.QRCodeDetectorAruco(), cv2.QRCodeDetector()):
        for width in (img.shape[1], 600, 300):
            small = cv2.resize(img, (width, width), interpolation=cv2.INTER_AREA)
            got = reader.detectAndDecode(small)[0]
            if got:
                return got
    return got


if __name__ == "__main__":
    width, n = make()
    print(f"docs/qr-slam.png: {width} x {width} pixels, {n} x {n} modules, link {LINK}")
    m = game()
    print(f"game/data/qr.js: {m} x {m} modules, the same link")
    if "--check" in sys.argv:
        got = check()
        if got != LINK:
            print(f"READ BACK DIFFERS: {got!r}")
            sys.exit(1)
        print("read back: the picture gives the exact link")
        got = check_game()
        if got != LINK:
            print(f"READ BACK OF game/data/qr.js DIFFERS: {got!r}")
            sys.exit(1)
        print("read back: the picture of the game gives the exact link")

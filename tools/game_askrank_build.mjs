// Makes game/core/askrank.js from js/math/askrank.js, so the web app (Ask me next, js/math/nextbest.js) and the game
// rank their open questions and stop asking with one function each (M8Y, run Finish everything partly built, Part 17).
// The game has classic scripts and no modules: this tool takes the word `export` off each declaration and adds the
// game's file header. Run it after each change of js/math/askrank.js, then the game steps (prettier, tools/game_stamp.cjs,
// tools/game_codemap.py). test/askrank.test.js and game/tests/asking-fewer-questions.js fail when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/askrank.js', import.meta.url), to = new URL('../game/core/askrank.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/askrank.js
   PURPOSE     Asking fewer questions (run Finish everything partly built, Part 17): the cost of not
               knowing in dollars (your money a year from now at both ends of a blank), one ranking of
               the open questions, and the stopping rule (stop once the questions asked cover 80% of
               what could move).
   INPUT       Plain numbers from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ')}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/askrank.js of the main app, the same
               ranking that Ask me next (js/math/nextbest.js) uses. tools/game_askrank_build.mjs makes
               it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/askrank.js written from js/math/askrank.js (${names.length} names, hash ${hash}).`);

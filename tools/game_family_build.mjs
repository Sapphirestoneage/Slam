// Family money is written once, in js/math/family.js (a module, no imports). SLAM the Game loads plain scripts with
// one global scope, so this tool writes the same code as a plain script: game/core/family.js. It removes the word
// "export", puts the game's file header on top, and adds two constants from the data files, so neither app types a
// number of its own: FM_REF (the dated New York rows of data/reference-2026.json: childcare, the 529 deduction, the
// federal K-12 limit) and FM_COMMUNITY (data/community-tuition.json, the community presets of the Yeshiva tuition
// goal). The web app reads the presets from js/data/community-tuition.js, which this tool writes too.
// Usage: node tools/game_family_build.mjs          write the copies
//        node tools/game_family_build.mjs --check  change nothing; exit 1 when a copy is stale
// Both test suites run the check (test/family.test.js, game/tests/family-money.js).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = p => new URL(`../${p}`, import.meta.url);
const HEAD = `/* ============================================================================
   SLAM the Game: core/family.js
   PURPOSE     Family money: the sandwich years (money to parents and kids at once), living at home
               (rent saved next to the time to a moving-out goal), and kids and tuition (childcare,
               school or yeshiva tuition, a 529 and the New York rules). The sheet "Family money"
               (features/family.js) uses it.
   INPUT       Numbers only. No profile, no screen.
   OUTPUT      Constants: FM_KINDS, FM_REF, FM_COMMUNITY. Functions: fmSandwich, fmBoomerang, fmCareRow,
               fmTuition, fm529, fmPresetRows.
   DEPENDS ON  Nothing.
   RULES       GENERATED FILE. Do not edit it. The source is js/math/family.js of the main SLAM app, with
               data/reference-2026.json and data/community-tuition.json, so the small pages of the web
               app and the game have one copy of each rule. To change a rule or a row, change the source,
               then run: node tools/game_family_build.mjs. The tests fail when this copy is stale.
               Prettier does not format this file (.prettierignore).
   ========================================================================= */
`;
const WEB_HEAD = `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by tools/game_family_build.mjs from data/community-tuition.json. Do not edit: change the data file, then
// run the tool. The community presets of the Yeshiva tuition goal (only rows with a label, a low and a high show).
`;
export function refRows() {
  const ref = JSON.parse(readFileSync(at('data/reference-2026.json'), 'utf8'));
  return { childcare: ref.childcare, ny529: ref.limits.ny529, k12From529: ref.limits.k12From529 };
}
export const community = () => JSON.parse(readFileSync(at('data/community-tuition.json'), 'utf8'));
export function built() {
  const src = readFileSync(at('js/math/family.js'), 'utf8');
  const body = src.split('\n').filter(l => !l.startsWith('// SPDX-License-Identifier')).join('\n').replace(/^export /gm, '');
  if (/^\s*import /m.test(body) || /\bexport\b/.test(body.replace(/\/\/.*$/gm, ''))) throw new Error('js/math/family.js must stay free of imports, and export only at the start of a line.');
  return `${HEAD}${body}// The dated rows (data/reference-2026.json) and the community presets (data/community-tuition.json).
const FM_REF = ${JSON.stringify(refRows())};
const FM_COMMUNITY = ${JSON.stringify(community())};
`;
}
export const builtWeb = () => `${WEB_HEAD}export const FM_COMMUNITY = ${JSON.stringify(community(), null, 2)};\n`;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outs = [[at('game/core/family.js'), built()], [at('js/data/community-tuition.js'), builtWeb()]];
  if (process.argv.includes('--check')) {
    const stale = outs.filter(([u, text]) => { try { return readFileSync(u, 'utf8') !== text; } catch { return true; } });
    if (stale.length) { console.log('game/core/family.js or js/data/community-tuition.js is stale. Run: node tools/game_family_build.mjs'); process.exit(1); }
    console.log('game/core/family.js and js/data/community-tuition.js match their sources.');
  } else { mkdirSync(at('js/data'), { recursive: true }); for (const [u, text] of outs) writeFileSync(u, text); console.log('game/core/family.js and js/data/community-tuition.js written.'); }
}

// Makes game/core/reportcore.js from js/report/core.js, so the web app and the game share one Report (the sheet, the
// list on the device, the sending, the admin inbox rows). The game has classic scripts and no modules: this tool takes
// the word `export` off each declaration and adds the game's file header. Run it after each change of
// js/report/core.js, then the game steps (prettier, tools/game_stamp.cjs, tools/game_codemap.py).
// test/report.test.js fails when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/report/core.js', import.meta.url), to = new URL('../game/core/reportcore.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:async function|function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/reportcore.js
   PURPOSE     Report a bug or idea: one report with the screen name, the last 3 taps, the device, the
               width and the app version; the list on the device; the sending to the database; the rows
               of the admin inbox; the sheet and its button.
   INPUT       Plain values from the caller, and the document for the sheet. It reads no profile.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  core/report.js (the error record), with a typeof test.
   RULES       Do not edit this file. It is a copy of js/report/core.js of the main app.
               tools/game_report_build.mjs makes it. Change the source, then run the tool.
               A report carries no money number: names of screens and buttons only.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/reportcore.js written from js/report/core.js (${names.length} names, hash ${hash}).`);

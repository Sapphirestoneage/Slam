// Makes game/core/enough.js from js/math/enough.js, so the web app and the game work out lifestyle creep, the enough
// number, the Pareto of spending and the Rough numbers ranges with one function each. The game has classic scripts and
// no modules: this tool takes the word `export` off each declaration and adds the game's file header. It also writes
// the dated CPI figure of data/reference-2026.json as EN_CPI, so the game reads the same row as the web app.
// Run it after each change of js/math/enough.js or of the CPI row, then the game steps (prettier, tools/game_stamp.cjs,
// tools/game_codemap.py). test/enough.test.js and game/tests/lifestyle-creep-and-enough.js fail when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/enough.js', import.meta.url), to = new URL('../game/core/enough.js', import.meta.url);
const ref = JSON.parse(readFileSync(new URL('../data/reference-2026.json', import.meta.url), 'utf8'));
const src = readFileSync(from, 'utf8');
const cpi = { value: ref.cpi.value, period: ref.cpi.period, source: ref.cpi.source, date: ref.cpi.date };
const hash = createHash('sha256').update(src + JSON.stringify(cpi)).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/enough.js
   PURPOSE     The math of Lifestyle creep and enough (run Not built, groups 1 to 5, Part 3): spending
               growth next to income growth per category, year over year, the lines that grow faster
               than inflation, the quiet card; the enough number and the room for error; the Pareto of
               spending; the ranges of Rough numbers.
   INPUT       Plain numbers and dates from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length + 1} functions and constants: EN_CPI, ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/enough.js of the main app, and EN_CPI is the
               CPI row of data/reference-2026.json. tools/game_enough_build.mjs makes it. Change the
               source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
/* The dated CPI figure (data/reference-2026.json, cpi): one tap among the player's own rates. */
const EN_CPI = ${JSON.stringify(cpi)};
`;
writeFileSync(to, head + body);
console.log(`game/core/enough.js written from js/math/enough.js (${names.length} names, hash ${hash}).`);

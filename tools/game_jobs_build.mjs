// Makes game/core/jobs.js from js/math/jobs.js, so the web app and the game work out the numbers of the six unpaid jobs
// with one function. The game has classic scripts and no modules: this tool takes the word `export` off each
// declaration and adds the game's file header. Run it after each change of js/math/jobs.js, then the game steps
// (prettier, tools/game_stamp.cjs, tools/game_codemap.py). test/jobs.test.js fails when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/jobs.js', import.meta.url), to = new URL('../game/core/jobs.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/jobs.js
   PURPOSE     The math of the Job of Existing (run JOE-1): which of the six unpaid jobs a player holds,
               from answers already given; the hours a month of running the money (Guess, Close,
               Exact); the minutes a month of each task; Running it and Living it; "1% better".
   INPUT       Plain numbers and dates from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/jobs.js of the main app.
               tools/game_jobs_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/jobs.js written from js/math/jobs.js (${names.length} names, hash ${hash}).`);

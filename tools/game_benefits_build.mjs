// Makes game/core/benefitsplan.js from js/math/benefitsplan.js, so the web app and the game work out the benefits
// optimizer, the health coverage chain, the plans side by side, the employer library and the health cliff with one
// function each. The game has classic scripts and no modules: this tool takes the word `export` off each declaration
// and adds the game's file header. It also writes BP_REF: the rows of data/reference-2026.json the engine reads (the
// poverty guideline, ref.benefits, ref.cliff's Medicaid, New York and marketplace rows) and data/library/employers.json,
// so the game reads the same rows as the web app (bpRules(BP_REF)).
// Run it after each change of js/math/benefitsplan.js or of those rows, then the game steps (prettier,
// tools/game_stamp.cjs, tools/game_codemap.py). test/benefitsplan.test.js fails when the copy is old.
// Usage: node tools/game_benefits_build.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const at = p => new URL(`../${p}`, import.meta.url);
export function built() {
  const ref = JSON.parse(readFileSync(at('data/reference-2026.json'), 'utf8')), lib = JSON.parse(readFileSync(at('data/library/employers.json'), 'utf8'));
  const src = readFileSync(at('js/math/benefitsplan.js'), 'utf8');
  const rows = { studentLoans: { poverty: ref.studentLoans.poverty }, benefits: ref.benefits, cliff: { medicaid: ref.cliff.medicaid, ny: ref.cliff.ny, aca: ref.cliff.aca }, tax: { socialSecurityRate: ref.tax.socialSecurityRate, medicareRate: ref.tax.medicareRate }, employers: lib };
  const hash = createHash('sha256').update(src + JSON.stringify(rows)).digest('hex').slice(0, 16);
  const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
  const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
  const head = `/* ============================================================================
   SLAM the Game: core/benefitsplan.js
   PURPOSE     The math of Benefits and health (run Finish everything partly built, Part 10): the
               benefits optimizer (HSA, dependent care FSA, ESPP, commuter), the health coverage chain,
               plans side by side, the employer library and the health cliff.
   INPUT       Plain numbers from the caller, and BP_REF (the reference rows). It reads no profile.
   OUTPUT      ${names.length + 1} functions and constants: BP_REF, ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/benefitsplan.js of the main app, and BP_REF
               is the rows of data/reference-2026.json and data/library/employers.json it reads.
               tools/game_benefits_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
/* The reference rows (data/reference-2026.json and data/library/employers.json), read with bpRules(BP_REF). */
const BP_REF = ${JSON.stringify(rows)};
`;
  return { text: head + body, hash };
}
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const { text, hash } = built(), to = at('game/core/benefitsplan.js');
  if (process.argv.includes('--check')) {
    const now = readFileSync(to, 'utf8');
    const m = now.match(/SOURCE-HASH {2}(\w+)/);
    if (!m || m[1] !== hash) { console.log('game/core/benefitsplan.js is stale. Run: node tools/game_benefits_build.mjs'); process.exit(1); }
    console.log('game/core/benefitsplan.js matches its sources.');
  } else { writeFileSync(to, text); console.log(`game/core/benefitsplan.js written from js/math/benefitsplan.js (hash ${hash}).`); }
}

// Makes game/core/ratios.js from js/math/ratios.js, so the web app and the game work out each ratio of Key numbers with
// one function (run Not built, groups 1 to 5, Part 9). The game has classic scripts and no modules: this tool takes the
// word `export` off each declaration and adds the game's file header.
// Run it after each change of js/math/ratios.js, then the game steps (prettier, tools/game_stamp.cjs,
// tools/game_codemap.py). test/ratios.test.js and game/tests/ratios-on-key-numbers.js fail when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/ratios.js', import.meta.url), to = new URL('../game/core/ratios.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/ratios.js
   PURPOSE     The math of Ratios on Key numbers (run Not built, groups 1 to 5, Part 9): one function
               for each ratio, the groups, the formula and the plain sentence of each line, and the
               rules of thumb with their source and date.
   INPUT       Plain numbers from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/ratios.js of the main app.
               tools/game_ratios_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/ratios.js written from js/math/ratios.js (${names.length} names, hash ${hash}).`);

// Makes game/core/recalc.js from js/math/recalc.js, so the web app and the game work out the Recalculating numbers
// with one function. The game has classic scripts and no modules: this tool takes the word `export` off each
// declaration and adds the game's file header. Run it after each change of js/math/recalc.js, then the game steps
// (prettier, tools/game_stamp.cjs, tools/game_codemap.py). test/recalc.test.js fails when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/recalc.js', import.meta.url), to = new URL('../game/core/recalc.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/recalc.js
   PURPOSE     The math of Recalculating: the route (old date, new date), the triage when the bills are
               more than the income, the emergency fund refill, the safe-to-fail line, the state of the
               month, and the opt-in audit that looks back.
   INPUT       Plain numbers and dates from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/recalc.js of the main app.
               tools/game_recalc_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/recalc.js written from js/math/recalc.js (${names.length} names, hash ${hash}).`);

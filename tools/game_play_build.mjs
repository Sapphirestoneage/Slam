// Makes game/core/play.js from js/math/play.js, so the web app and the game work out the daily challenge, the credit
// score game and the bank bonus hunt with one function each (run Not built, groups 1 to 5, Part 10b). The game has
// classic scripts and no modules: this tool takes the word `export` off each declaration, takes the import line off
// (the game has qcGrow from core/quick.js, loaded first), and adds the game's file header.
// Usage: node tools/game_play_build.mjs          write the copy
//        node tools/game_play_build.mjs --check  change nothing; exit 1 when the copy is stale
// test/play.test.js and game/tests/play-and-people.js fail when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/play.js', import.meta.url), to = new URL('../game/core/play.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^import .*\n/gm, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/play.js
   PURPOSE     The math of the play parts (run Not built, groups 1 to 5, Part 10b): the daily life-sim
               challenge, the credit score game (myFICO's five factor shares) and the first $1,000 bonus
               hunt with its bank bonus calculator.
   INPUT       Plain numbers from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  core/quick.js (qcGrow).
   RULES       Do not edit this file. It is a copy of js/math/play.js of the main app.
               tools/game_play_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
let old = '';
try { old = readFileSync(to, 'utf8'); } catch {}
if (process.argv.includes('--check')) {
  const ok = old.includes('SOURCE-HASH  ' + hash);
  console.log(ok ? 'game/core/play.js is current.' : 'game/core/play.js is stale: run node tools/game_play_build.mjs');
  process.exit(ok ? 0 : 1);
}
writeFileSync(to, head + body);
console.log(`game/core/play.js written from js/math/play.js (${names.length} names, hash ${hash}).`);

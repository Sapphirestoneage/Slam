// Makes game/core/exercises.js from js/exercises/catalog.js, so the web app and the game show the same Exercises
// list, the same prompts and the same privacy rule (run "Finish everything partly built", Part 7). The game has
// classic scripts and no modules: this tool takes the word `export` off each declaration and adds the game's file
// header. Run it after each change of js/exercises/catalog.js, then the game steps (prettier, tools/game_stamp.cjs,
// tools/game_codemap.py). test/exercises.test.js and game/tests/money-exercises.js fail when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/exercises/catalog.js', import.meta.url), to = new URL('../game/core/exercises.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/exercises.js
   PURPOSE     The list of the Exercises screen (run Finish everything partly built, Part 7, Money
               psychology): ten money exercises and three prompts for life after work, each with a
               short prompt and lines to tap; the who-sees rule; the voice-to-text note.
   INPUT       Plain text from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/exercises/catalog.js of the main app.
               tools/game_exercises_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/exercises.js written from js/exercises/catalog.js (${names.length} names, hash ${hash}).`);

// Makes game/core/sins.js from js/math/sins.js, so the web app and the game read the money sins (the evidence, the
// fading, the two-sources rule, the check-ins, the push-back and Test the fix) with one function. The game has classic scripts and no modules: this tool takes the word `export` off each
// declaration and adds the game's file header. Run it after each change of js/math/sins.js, then the game steps
// (prettier, tools/game_stamp.cjs, tools/game_codemap.py). test/sins.test.js fails when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/sins.js', import.meta.url), to = new URL('../game/core/sins.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/sins.js
   PURPOSE     The money sins read: the evidence of four sources (the quiz, the ledger, the one-tap
               check-ins, the reactions to the app) as weighted pieces that fade with time, the rule that
               a label shows only when two sources agree over about 30 days, the top two of each family,
               "Why we think this", the push-back, and Test the fix. The scoring is the quiz engine.
               Part 2: the result card and its archetype, the share card with no numbers, the framing
               line for a type and a moment, couples, the retake each quarter and the history of reads.
               Part 3: the Rings theme, its rulers, the rings climbed and the boss.
   INPUT       Plain data and dates from the caller, and the engine (qzResult). It reads no profile.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing (the caller hands in core/quizcore.js).
   RULES       Do not edit this file. It is a copy of js/math/sins.js of the main app.
               tools/game_sins_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/sins.js written from js/math/sins.js (${names.length} names, hash ${hash}).`);

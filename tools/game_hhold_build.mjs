// Makes game/core/hhold.js from js/math/hhold.js, so the web app and the game work out the numbers of Households (Part 12)
// with one function. The game has classic scripts and no modules: this tool takes the word `export` off each
// declaration and adds the game's file header. Run it after each change of js/math/hhold.js, then the game steps
// (prettier, tools/game_stamp.cjs, tools/game_codemap.py). test/hhold.test.js fails when the copy is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const from = new URL('../js/math/hhold.js', import.meta.url), to = new URL('../game/core/hhold.js', import.meta.url);
const src = readFileSync(from, 'utf8');
const hash = createHash('sha256').update(src).digest('hex').slice(0, 16);
const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
const head = `/* ============================================================================
   SLAM the Game: core/hhold.js
   PURPOSE     The math of Households (run Finish everything partly built, Part 12): the same
               question for everyone and its talk points, the answer code for two phones, FI
               together, a shared home's equity, the tax gap when two marry, the email draft.
   INPUT       Plain numbers and dates from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/hhold.js of the main app.
               tools/game_hhold_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
writeFileSync(to, head + body);
console.log(`game/core/hhold.js written from js/math/hhold.js (${names.length} names, hash ${hash}).`);

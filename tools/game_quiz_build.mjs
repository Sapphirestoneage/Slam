// The one quiz engine, shared by the web app and the game (docs/QUIZ-ENGINE.md). This tool writes three files:
//   game/core/quizcore.js    a copy of js/math/quizcore.js (the engine). The game has classic scripts and no modules:
//                            the tool takes the word `export` off each declaration and adds the game's file header.
//   game/data/quizskins.js   the quiz skins (js/quiz/skins/index.js) as data, with the routes below.
//   data/quiz/routes.json    the skills, skill trees and readings the skins route to, by id, with their names, read
//                            from data/library/skills.json and data/library/unlearn.json (so no name is typed twice).
// Run it after each change of the engine or of a skin, then the game steps (prettier, tools/game_stamp.cjs,
// tools/game_codemap.py). test/quizcore.test.js and game/tests/quizzes.js fail when a file is old.
// `node tools/game_quiz_build.mjs --check` writes nothing and exits 1 when a file is old.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { SKINS } from '../js/quiz/skins/index.js';
import { qzIds } from '../js/math/quizcore.js';

const at = p => new URL(`../${p}`, import.meta.url), read = p => readFileSync(at(p), 'utf8'), json = p => JSON.parse(read(p));
const sha = s => createHash('sha256').update(s).digest('hex').slice(0, 16);

// 1 the engine
export function coreCopy() {
  const src = read('js/math/quizcore.js'), hash = sha(src);
  const body = src.replace(/^\/\/ SPDX-License-Identifier:.*\n/, '').replace(/^export /gm, '');
  const names = [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map(m => m[1]);
  const head = `/* ============================================================================
   SLAM the Game: core/quizcore.js
   PURPOSE     The one quiz engine: the questions a set of answers leads to, the scoring (with scores
               from outside as an input), ties, the top two, the confidence level, the result card,
               the routes to skills and readings, and how a result leans on the five elements.
   INPUT       A quiz definition (data/quizskins.js, or MC_QUIZ in features/chart.js) and plain
               answers from the caller. It reads no profile and no screen.
   OUTPUT      ${names.length} functions and constants: ${names.join(', ').replace(/(.{1,84})(, |$)/g, '$1$2\n               ').trimEnd()}
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. It is a copy of js/math/quizcore.js of the main app.
               tools/game_quiz_build.mjs makes it. Change the source, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
  return { path: 'game/core/quizcore.js', text: head + body, hash, names };
}
// 2 the routes: each id a skin names, with its name from the library. An id that is not in the library stops the build.
export function routesOf() {
  const lib = json('data/library/skills.json'), un = json('data/library/unlearn.json');
  const ids = SKINS.map(qzIds), all = k => [...new Set(ids.flatMap(i => i[k]))].sort();
  const routes = { skills: {}, trees: {}, readings: {} }, missing = [];
  for (const id of all('skills')) { const s = lib.skills.find(x => x.id === id); if (!s) missing.push(`skill ${id}`); else routes.skills[id] = { name: s.name, what: s.description, tree: s.tree, treeName: s.treeName, level: s.level }; }
  for (const id of all('trees')) { const t = lib.trees.find(x => x.id === id); if (!t) missing.push(`tree ${id}`); else routes.trees[id] = { name: t.name }; }
  for (const id of all('readings')) { const r = un.entries.find(x => x.id === id); if (!r) missing.push(`reading ${id}`); else routes.readings[id] = { advice: r.advice, line: r.line }; }
  if (missing.length) throw new Error(`A skin routes to an id that is not in data/library: ${missing.join(', ')}`);
  return routes;
}
export function routesFile() {
  const routes = routesOf();
  const doc = { id: 'quiz.routes', note: 'Made by tools/game_quiz_build.mjs from the quiz skins (js/quiz/skins) and data/library. Do not edit: change the skin or the library, then run the tool.', ...routes };
  return { path: 'data/quiz/routes.json', text: JSON.stringify(doc, null, 1) + '\n', routes };
}
// 3 the skins, as data for the game
export function skinsCopy() {
  const routes = routesOf(), data = JSON.parse(JSON.stringify(SKINS)), hash = sha(JSON.stringify({ data, routes }));
  const head = `/* ============================================================================
   SLAM the Game: data/quizskins.js
   PURPOSE     Data only. The quiz skins of the one quiz engine (${data.map(s => s.id).join(', ')}),
               and the skills, skill trees and readings that their cards route to.
   INPUT       Nothing.
   OUTPUT      Constants that the other files read: QZ_SKINS, QZ_ROUTES.
   DEPENDS ON  Nothing.
   RULES       Do not edit this file. tools/game_quiz_build.mjs makes it from js/quiz/skins/ of the
               main app and from data/library. Change a skin there, then run the tool.
   SOURCE-HASH  ${hash}
   ========================================================================= */
`;
  return { path: 'game/data/quizskins.js', text: `${head}window.QZ_SKINS = ${JSON.stringify(data, null, 2)};\nwindow.QZ_ROUTES = ${JSON.stringify(routes, null, 2)};\n`, hash };
}
// What is old: the engine copy and the skins copy by their SOURCE-HASH (prettier may format the copies), the routes word for word.
export function stale() {
  const old = [], has = (p, hash) => { try { return read(p).includes(`SOURCE-HASH  ${hash}`); } catch { return false; } };
  const c = coreCopy(), s = skinsCopy(), r = routesFile();
  if (!has(c.path, c.hash)) old.push(c.path);
  if (!has(s.path, s.hash)) old.push(s.path);
  let now = null; try { now = read(r.path); } catch { now = null; }
  if (now !== r.text) old.push(r.path);
  return old;
}
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  if (process.argv.includes('--check')) { const old = stale(); console.log(old.length ? `OLD: ${old.join(', ')}. Run: node tools/game_quiz_build.mjs` : 'The quiz copies are current.'); process.exit(old.length ? 1 : 0); }
  for (const f of [coreCopy(), skinsCopy(), routesFile()]) { writeFileSync(at(f.path), f.text); console.log(`${f.path} written${f.hash ? ` (hash ${f.hash})` : ''}.`); }
}
